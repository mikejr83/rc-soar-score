# scripts/generate-enum-catalog.ps1
# Builds plan/data-model/enumerations.md from the entity documents and marks
# every enumeration column in plan/data-model/ERD.md with an "enum" comment.
#
# An enumeration field is any row in an entity's Fields/Properties table whose
# Type column starts with "enum" (any case, with or without an inline value
# list). The catalog repeats each field's documented definition verbatim, so
# the entity document stays the single source of truth for allowed values.
#
# Default: write the catalog and update the ERD (idempotent).
# -Check:  write nothing; exit 1 if the catalog or ERD are out of date, or if
#          an enumeration field has no matching column in the ERD.
# Exit code 0 = up to date, 1 = changes needed or problems found.

param([switch]$Check)

$ErrorActionPreference = 'Stop'
$scriptDir = Split-Path -Parent $MyInvocation.MyCommand.Path
$root = Split-Path -Parent $scriptDir
$dataModel = Join-Path $root 'plan\data-model'
$entityDir = Join-Path $dataModel 'entities'
$erdPath = Join-Path $dataModel 'ERD.md'
$catalogPath = Join-Path $dataModel 'enumerations.md'

function Split-Row([string]$line) {
    # Split a Markdown table row on unescaped pipes; drop the outer empties.
    $cells = [regex]::Split($line, '(?<!\\)\|')
    return @($cells[1..($cells.Count - 2)] | ForEach-Object { $_.Trim() })
}

function Get-Key([string]$name) { return ($name -replace '[_\s]', '').ToLowerInvariant() }

# --- Collect enumeration fields from the entity documents ---------------
$fields = [System.Collections.Generic.List[object]]::new()
foreach ($file in Get-ChildItem -LiteralPath $entityDir -Filter '*.md' | Sort-Object Name) {
    $lines = [System.IO.File]::ReadAllLines($file.FullName)
    $title = (($lines | Where-Object { $_ -match '^# ' } | Select-Object -First 1) -replace '^# ', '').Trim()
    $inFields = $false
    $columns = $null
    foreach ($line in $lines) {
        if ($line -match '^## Fields') { $inFields = $true; continue }
        if ($inFields -and $line -match '^## ') { break }
        if (-not $inFields -or $line -notmatch '^\|') { continue }
        $cells = Split-Row $line
        if ($cells[0] -match '^Field$') { $columns = $cells; continue }
        if ($null -eq $columns -or $cells[0] -match '^-+$|^:?-+:?$') { continue }
        $name = $cells[0].Trim('`')
        $type = $cells[[array]::IndexOf($columns, 'Type')]
        if ($type -notmatch '^(?i)enum') { continue }
        $get = {
            param($column)
            $i = [array]::IndexOf($columns, $column)
            if ($i -ge 0 -and $i -lt $cells.Count) { $cells[$i] } else { '-' }
        }
        $fields.Add([pscustomobject]@{
            Title = $title
            File = $file.Name
            Key = Get-Key ([System.IO.Path]::GetFileNameWithoutExtension($file.Name))
            Field = $name
            Type = $type
            Required = (& $get 'Required')
            Default = (& $get 'Default')
            Definition = (& $get 'Description')
        })
    }
}

# --- Build the catalog ---------------------------------------------------
$out = [System.Collections.Generic.List[string]]::new()
$out.Add('# Enumerations')
$out.Add('')
$out.Add('Every enumeration field in the data model, generated from the entity documents by `scripts/generate-enum-catalog.ps1`. Do not edit this file by hand: change the entity document and run the script. Each definition is repeated verbatim from the entity document, which is the source of truth for allowed values. Enumerations are stored as text constrained to the listed values, and an enumeration column is marked `enum` in the [ERD](ERD.md). Contest-level options, including their allowed values and defaults, are in [contest-options.md](contest-options.md).')
$out.Add('')
$out.Add("$($fields.Count) enumeration fields in $((@($fields | Select-Object -ExpandProperty File -Unique)).Count) entities.")
$out.Add('')
$out.Add('| Entity | Field | Required | Default | Definition |')
$out.Add('| ------ | ----- | -------- | ------- | ---------- |')
foreach ($f in $fields) {
    $out.Add("| [$($f.Title)](entities/$($f.File)) | ``$($f.Field)`` | $($f.Required) | $($f.Default) | $($f.Definition) |")
}
$catalog = ($out -join "`n") + "`n"

# --- Mark the ERD ----------------------------------------------------------
$erdLines = [System.IO.File]::ReadAllLines($erdPath)
$problems = [System.Collections.Generic.List[string]]::new()
$blockKey = $null
$changed = $false
for ($i = 0; $i -lt $erdLines.Count; $i++) {
    if ($erdLines[$i] -match '^\s+([A-Z][A-Z0-9_]*) \{\s*$') { $blockKey = Get-Key $Matches[1]; continue }
    if ($erdLines[$i] -match '^\s+\}\s*$') { $blockKey = $null; continue }
    if ($null -eq $blockKey) { continue }
    if ($erdLines[$i] -notmatch '^(?<indent>\s+)(?<type>\S+)(?<gap>\s+)(?<name>[a-z][a-z0-9_]*)(?<keys>(?:\s+(?:PK|FK|UK)(?:,\s*(?:PK|FK|UK))*)?)(?:(?<gap2>\s+)"(?<note>[^"]*)")?\s*$') { continue }
    $isEnum = $fields | Where-Object { $_.Key -eq $blockKey -and $_.Field -eq $Matches['name'] }
    if (-not $isEnum) { continue }
    $note = $Matches['note']
    if ($note -match '^enum(,|$)') { continue }
    $newNote = if ($note) { "enum, $note" } else { 'enum' }
    $gap2 = if ($Matches['gap2']) { $Matches['gap2'] } else { '    ' }
    $erdLines[$i] = "$($Matches['indent'])$($Matches['type'])$($Matches['gap'])$($Matches['name'])$($Matches['keys'])$gap2`"$newNote`""
    $changed = $true
}
# Every enumeration field must now be marked in the ERD.
$marked = @{}
$blockKey = $null
foreach ($line in $erdLines) {
    if ($line -match '^\s+([A-Z][A-Z0-9_]*) \{\s*$') { $blockKey = Get-Key $Matches[1]; continue }
    if ($line -match '^\s+\}\s*$') { $blockKey = $null; continue }
    if ($blockKey -and $line -match '^\s+\S+\s+([a-z][a-z0-9_]*)\b.*"enum(,[^"]*)?"\s*$') { $marked["$blockKey/$($Matches[1])"] = $true }
}
foreach ($f in $fields) {
    if (-not $marked.ContainsKey("$($f.Key)/$($f.Field)")) {
        $problems.Add("ERD has no column for enumeration field $($f.Title).$($f.Field)")
    }
}
$extra = $marked.Keys | Where-Object { $k = $_; -not ($fields | Where-Object { "$($_.Key)/$($_.Field)" -eq $k }) }
foreach ($k in $extra) { $problems.Add("ERD marks $k as enum but the entity document does not") }

# --- Write or check --------------------------------------------------------
$existingCatalog = if (Test-Path -LiteralPath $catalogPath) { [System.IO.File]::ReadAllText($catalogPath) -replace "`r`n", "`n" } else { '' }
# Prettier realigns tables, so compare without column padding or separator width.
function Get-Normalized([string]$text) { return ($text -replace '-{2,}', '-' -replace '\s+', ' ').Trim() }
$catalogStale = (Get-Normalized $catalog) -ne (Get-Normalized $existingCatalog)
foreach ($p in $problems) { Write-Host "PROBLEM  $p" }

if ($Check) {
    if ($catalogStale) { Write-Host 'STALE    enumerations.md is out of date (run scripts/generate-enum-catalog.ps1; run Prettier afterwards)' }
    if ($changed) { Write-Host 'STALE    ERD.md has enumeration columns without an enum marker' }
    Write-Host "$($fields.Count) enumeration fields, $($problems.Count) problem(s)."
    if ($problems.Count -or $changed) { exit 1 }
    exit 0
}

[System.IO.File]::WriteAllText($catalogPath, $catalog)
if ($changed) { [System.IO.File]::WriteAllText($erdPath, ($erdLines -join "`n") + "`n") }
Write-Host "$($fields.Count) enumeration fields. Catalog written; ERD $(if ($changed) { 'updated' } else { 'already marked' })."
if ($problems.Count) { exit 1 }
exit 0
